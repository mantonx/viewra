// Command taskgen generates scheduler task registration code.
//
// It scans internal/application/*/tasks.go files for packages that export
// a `Tasks` variable of type `[]scheduler.TaskBuilder`, then generates
// internal/app/scheduler_tasks_gen.go with all imports and registration code.
//
// Usage:
//
//	go run ./cmd/taskgen
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
	"time"

	"golang.org/x/tools/imports"
)

const (
	applicationDir = "internal/application"
	outputFile     = "internal/app/scheduler_tasks_gen.go"
	schedulerPkg   = "github.com/mantonx/viewra/internal/application/scheduler"
)

type packageInfo struct {
	Name       string // package name (e.g., "scanjob")
	ImportPath string // full import path
	TasksVar   string // name of the exported Tasks variable
}

func main() {
	packages, err := discoverTaskPackages()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error discovering task packages: %v\n", err)
		os.Exit(1)
	}

	if len(packages) == 0 {
		fmt.Println("No task packages found")
		return
	}

	fmt.Printf("Found %d task packages:\n", len(packages))
	for _, pkg := range packages {
		fmt.Printf("  - %s (%s)\n", pkg.Name, pkg.ImportPath)
	}

	code, err := generateCode(packages)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error generating code: %v\n", err)
		os.Exit(1)
	}

	// Format with goimports
	formatted, err := imports.Process(outputFile, code, nil)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error formatting code: %v\n", err)
		// Write unformatted for debugging
		os.WriteFile(outputFile+".err", code, 0644)
		os.Exit(1)
	}

	if err := os.WriteFile(outputFile, formatted, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing output: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s\n", outputFile)
}

func discoverTaskPackages() ([]packageInfo, error) {
	var packages []packageInfo

	// Get the module path
	modulePath, err := getModulePath()
	if err != nil {
		return nil, fmt.Errorf("failed to get module path: %w", err)
	}

	// Walk internal/application looking for tasks.go files
	err = filepath.Walk(applicationDir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		// Only look at tasks.go files
		if info.IsDir() || info.Name() != "tasks.go" {
			return nil
		}

		// Parse the file
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Warning: failed to parse %s: %v\n", path, err)
			return nil
		}

		// Check if it has an exported Tasks variable
		hasTasksVar := false
		for _, decl := range f.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.VAR {
				continue
			}
			for _, spec := range genDecl.Specs {
				valueSpec, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for _, name := range valueSpec.Names {
					if name.Name == "Tasks" && name.IsExported() {
						hasTasksVar = true
						break
					}
				}
			}
		}

		if hasTasksVar {
			dir := filepath.Dir(path)
			importPath := filepath.Join(modulePath, dir)
			importPath = strings.ReplaceAll(importPath, string(filepath.Separator), "/")

			packages = append(packages, packageInfo{
				Name:       f.Name.Name,
				ImportPath: importPath,
				TasksVar:   "Tasks",
			})
		}

		return nil
	})

	if err != nil {
		return nil, err
	}

	// Sort by package name for consistent output
	sort.Slice(packages, func(i, j int) bool {
		return packages[i].Name < packages[j].Name
	})

	return packages, nil
}

func getModulePath() (string, error) {
	data, err := os.ReadFile("go.mod")
	if err != nil {
		return "", err
	}

	lines := strings.Split(string(data), "\n")
	for _, line := range lines {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "module ") {
			return strings.TrimPrefix(line, "module "), nil
		}
	}

	return "", fmt.Errorf("module path not found in go.mod")
}

func generateCode(packages []packageInfo) ([]byte, error) {
	tmpl := template.Must(template.New("gen").Parse(codeTemplate))

	data := struct {
		GeneratedAt string
		Packages    []packageInfo
	}{
		GeneratedAt: time.Now().Format(time.RFC3339),
		Packages:    packages,
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}

const codeTemplate = `// Code generated by taskgen. DO NOT EDIT.
// Generated at: {{.GeneratedAt}}

package app

import (
	"context"

	"github.com/mantonx/viewra/internal/application/scheduler"
	domscheduler "github.com/mantonx/viewra/internal/domain/scheduler"
{{range .Packages}}
	"{{.ImportPath}}"
{{- end}}
)

// RegisterAllTasks registers all discovered scheduled tasks.
func RegisterAllTasks(ctx context.Context, svc *scheduler.Service, deps *scheduler.RuntimeDeps) error {
	logger := deps.Logger

	// Collect all task builders from discovered packages
	var builders []scheduler.TaskBuilder
{{range .Packages}}
	builders = append(builders, {{.Name}}.Tasks...)
{{- end}}

	for _, builder := range builders {
		def := builder.Definition()
		handler := builder.Build(deps)

		// Skip tasks that return nil handler (e.g., optional features disabled)
		if handler == nil {
			logger.Debug("Skipping disabled task", "task_id", def.ID)
			continue
		}

		timeout := def.TimeoutSeconds
		if timeout == 0 {
			timeout = 300 // Default 5 minutes
		}

		if err := svc.RegisterInternalTask(ctx, domscheduler.InternalTask{
			ID:             def.ID,
			Name:           def.Name,
			Description:    def.Description,
			Schedule:       def.Schedule,
			Handler:        handler,
			TimeoutSeconds: timeout,
		}, def.Group); err != nil {
			logger.Error("Failed to register task", "task_id", def.ID, "error", err)
		}
	}

	logger.Info("Registered internal scheduled tasks")
	return nil
}
`
