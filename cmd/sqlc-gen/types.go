package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// generateTypeAliases creates type aliases in the unified package that point
// to SQLite types. Since both backends generate identical types after
// normalization, repositories can use these aliases regardless of database.
func generateTypeAliases(cfg Config) error {
	types, err := extractTypes(cfg.SQLiteDir)
	if err != nil {
		return fmt.Errorf("extracting types: %w", err)
	}

	// Separate into categories
	var models, params, rows []string
	for _, t := range types {
		switch {
		case strings.HasSuffix(t, "Params"):
			params = append(params, t)
		case strings.HasSuffix(t, "Row"):
			rows = append(rows, t)
		default:
			models = append(models, t)
		}
	}

	// Generate output
	sqliteImport := cfg.ModulePath + "/" + cfg.SQLiteDir

	var buf bytes.Buffer
	buf.WriteString(`// Code generated by sqlc-gen. DO NOT EDIT.
// Regenerate with: make sqlc-gen
//
// Unified Type Aliases
// --------------------
// Viewra supports both SQLite and PostgreSQL. SQLC generates separate type
// definitions for each database, but after normalization they are structurally
// identical. This file creates type aliases pointing to the SQLite types,
// which repositories can use regardless of which database is active.
//
// This eliminates the need for duplicate type definitions and converters
// throughout the codebase.

package unified

import (
	"` + sqliteImport + `"
)

// Model type aliases - database table models
type (
`)
	for _, t := range models {
		fmt.Fprintf(&buf, "\t%s = sqlc_sqlite.%s\n", t, t)
	}
	buf.WriteString(`)

// Params type aliases - these represent query input parameters.
type (
`)
	for _, t := range params {
		fmt.Fprintf(&buf, "\t%s = sqlc_sqlite.%s\n", t, t)
	}
	buf.WriteString(`)

// Row type aliases - these represent query result rows.
type (
`)
	for _, t := range rows {
		fmt.Fprintf(&buf, "\t%s = sqlc_sqlite.%s\n", t, t)
	}
	buf.WriteString(")\n")

	if err := os.WriteFile(cfg.TypesFile, buf.Bytes(), 0644); err != nil {
		return fmt.Errorf("writing output: %w", err)
	}

	fmt.Printf("  Generated %s with %d types (%d models, %d params, %d rows)\n",
		cfg.TypesFile, len(types), len(models), len(params), len(rows))
	return nil
}

// extractTypes parses all exported types from a package directory.
func extractTypes(dir string) ([]string, error) {
	typeSet := make(map[string]bool)

	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	for _, file := range files {
		f, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			return nil, fmt.Errorf("parsing %s: %w", file, err)
		}

		for _, decl := range f.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}

			for _, spec := range genDecl.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}

				name := typeSpec.Name.Name
				if !ast.IsExported(name) {
					continue
				}
				// Skip interfaces (we define those separately)
				if name == "Querier" || name == "DBTX" {
					continue
				}

				typeSet[name] = true
			}
		}
	}

	types := make([]string, 0, len(typeSet))
	for t := range typeSet {
		types = append(types, t)
	}
	sort.Strings(types)
	return types, nil
}
